const letterVariations: Record<string, string> = {
  'ا': 'ا', 'أ': 'ا', 'إ': 'ا', 'ٱ': 'ا', 'آ': 'ا',
  'ى': 'ي', 'ي': 'ي', 'ئ': 'ي', 'ؤ': 'و', 'ء': 'ء',
  'ة': 'ة', 'ه': 'ه',
};

function normalizeArabic(text: string): string {
  return text.replace(/[\u064B-\u0652\u0670]/g, '');
}

function normalizeLetter(char: string): string {
  const normalized = letterVariations[char];
  return normalized !== undefined ? normalized : char;
}

function normalizeWord(text: string): string {
  return [...text].map(normalizeLetter).join('');
}

function stripTashkeel(text: string): string {
  return text.replace(/[\u064B-\u0652\u0670]/g, '');
}

export default function WritingScreen() {
  const { level } = useLocalSearchParams();
  const router = useRouter();
  const [number, setNumber] = useState(0);
  const [typedText, setTypedText] = useState('');
  const [showSuccess, setShowSuccess] = useState(false);
  const [loading, setLoading] = useState(true);
  const [showComplete, setShowComplete] = useState(false);

  const words = wordData[level as string] || basicWords;
  const currentWord = words[number];
  const [correctWords, setCorrectWords] = useState<string[]>([]);
  const correctWordsRef = useRef<string[]>([]);
  correctWordsRef.current = correctWords;

  useEffect(() => {
    const loadCorrectWords = async () => {
      setLoading(true);
      try {
        const stored = await AsyncStorage.getItem(`correctWords_${level}`);
        if (stored) {
          setCorrectWords(JSON.parse(stored));
        }
      } catch (e) {}
      setLoading(false);
    };
    loadCorrectWords();
  }, [level]);

  const saveCorrectWord = async (word: string) => {
    try {
      const newCorrect = [...correctWords, word];
      setCorrectWords(newCorrect);
      await AsyncStorage.setItem(`correctWords_${level}`, JSON.stringify(newCorrect));
      if (newCorrect.length >= words.length) {
        setShowComplete(true);
      }
    } catch (e) {}
  };
  const normalizedWord = normalizeWord(normalizeArabic(currentWord));

  useEffect(() => {
    if (loading) return;
    if (correctWords.length >= words.length) {
      setShowComplete(true);
      return;
    }
    const availableWords = words.filter((w: string) => !correctWords.includes(w));
    if (availableWords.length > 0) {
      setNumber(words.indexOf(availableWords[Math.floor(Math.random() * availableWords.length)]));
    } else {
      setNumber(Math.floor(Math.random() * words.length));
    }
  }, [level, loading, correctWords]);

  useEffect(() => {
    setTypedText('');
    setShowSuccess(false);
  }, [number]);

  useEffect(() => {
    const typedGroups = groupChars(typedText);
    const correctGroups = groupChars(currentWord);
    const isExactMatch = typedGroups.length === correctGroups.length && 
      typedGroups.every((g, i) => g === correctGroups[i]);
    if (isExactMatch && typedText.length > 0) {
      setShowSuccess(true);
      if (!correctWords.includes(currentWord)) {
        saveCorrectWord(currentWord);
      }
      const timer = setTimeout(() => {
        const availableWords = words.filter((w: string) => !correctWordsRef.current.includes(w));
        if (availableWords.length > 0) {
          setNumber(words.indexOf(availableWords[Math.floor(Math.random() * availableWords.length)]));
        } else {
          setNumber(Math.floor(Math.random() * words.length));
        }
      }, 3000);
      return () => clearTimeout(timer);
    }
  }, [typedText]);

  function groupChars(word: string): string[] {
    const chars = [...word];
    const groups: string[] = [];
    let i = 0;
    while (i < chars.length) {
      if (/[\u064B-\u0652\u0670]/.test(chars[i])) {
        i++;
        continue;
      }
      let group = chars[i];
      i++;
      while (i < chars.length && /[\u064B-\u0652\u0670]/.test(chars[i])) {
        group += chars[i];
        i++;
      }
      groups.push(group);
    }
    return groups;
  }

  const getTypedColor = () => {
    if (showSuccess) return '#4CAF50';
    if (typedText.length === 0) return '#666';
    
    const typedGroups = groupChars(typedText);
    const correctGroups = groupChars(currentWord);
    
    let hasWrongLetter = false;
    let hasMissingTashkeel = false;
    
    for (let i = 0; i < typedGroups.length; i++) {
      const typed = typedGroups[i];
      const correct = correctGroups[i];
      
      if (!correct) {
        hasWrongLetter = true;
        break;
      }
      
      if (typed === correct) continue;
      
      const typedBase = stripTashkeel(typed);
      const correctBase = stripTashkeel(correct);
      
      if (typedBase !== correctBase) {
        hasWrongLetter = true;
        break;
      }
      
      hasMissingTashkeel = true;
    }
    
    if (hasWrongLetter) return '#F44336';
    if (hasMissingTashkeel) return '#FF9800';
    return '#4CAF50';
  };

  const isRed = (text: string) => {
    if (text.length === 0) return false;
    const typedGroups = groupChars(text);
    const correctGroups = groupChars(currentWord);
    for (let i = 0; i < typedGroups.length; i++) {
      const typed = typedGroups[i];
      const correct = correctGroups[i];
      if (!correct) return true;
      if (typed === correct) continue;
      const typedBase = stripTashkeel(typed);
      const correctBase = stripTashkeel(correct);
      if (typedBase !== correctBase) return true;
    }
    return false;
  };

  const isOrange = (text: string) => {
    if (text.length === 0) return false;
    const typedGroups = groupChars(text);
    const correctGroups = groupChars(currentWord);
    let hasMissingTashkeel = false;
    for (let i = 0; i < typedGroups.length; i++) {
      const typed = typedGroups[i];
      const correct = correctGroups[i];
      if (!correct) continue;
      if (typed === correct) continue;
      const typedBase = stripTashkeel(typed);
      const correctBase = stripTashkeel(correct);
      if (typedBase === correctBase) {
        hasMissingTashkeel = true;
      }
    }
    return hasMissingTashkeel && !isRed(text);
  };

  const isTashkeel = (char: string) => /[\u064B-\u0652\u0670]/.test(char);

  const handleLetterPress = (letter: string) => {
    if (isRed(typedText)) {
      return;
    }
    if (isOrange(typedText) && !isTashkeel(letter)) {
      return;
    }
    setTypedText((prev) => prev + letter);
  };

  const KeyButton = ({ letter, onPress, style, textStyle, isTashkeelKey }: {
    letter: string;
    onPress: () => void;
    style?: object;
    textStyle?: object;
    isTashkeelKey?: boolean;
  }) => {
    const scaleAnim = useRef(new Animated.Value(1));
    const canPress = !isTashkeelKey 
      ? (!isRed(typedText) && (!isOrange(typedText) || isTashkeel(letter)))
      : (!isRed(typedText));

    const handlePressIn = () => {
      if (!canPress) return;
      Animated.spring(scaleAnim.current, {
        toValue: 0.85,
        useNativeDriver: true,
      }).start();
    };

    const handlePressOut = () => {
      Animated.spring(scaleAnim.current, {
        toValue: 1,
        useNativeDriver: true,
      }).start();
    };

    return (
      <Animated.View style={{ transform: [{ scale: scaleAnim.current }] }}>
        <Pressable
          onPress={onPress}
          onPressIn={handlePressIn}
          onPressOut={handlePressOut}
          style={[style, !canPress && { opacity: 0.4 }]}
        >
          <Text style={textStyle}>{letter}</Text>
        </Pressable>
      </Animated.View>
    );
  };

  return (
    <View style={styles.container}>
      <View style={styles.header}>
        <Text style={styles.wordText}>{currentWord}</Text>
        <View style={styles.typedRow}>
          <View style={styles.iconColumn}>
            <Text style={styles.statusEmoji}>
              {typedText.length === 0 ? '' : getTypedColor() === '#4CAF50' ? '👍' : getTypedColor() === '#FF9800' ? '😳' : '😡'}
            </Text>
          </View>
          <View style={styles.textColumn}>
            <Text style={[styles.typedText, { color: getTypedColor() }]}>
              {typedText || '...'}
            </Text>
          </View>
          <View style={styles.iconColumn}>
            <Pressable style={styles.deleteButton} onPress={() => setTypedText((prev) => prev.slice(0, -1))}>
              <Text style={styles.deleteButtonText}>⌫</Text>
            </Pressable>
          </View>
        </View>
        
      </View>
<View style={styles.keyboardContainer}>
        <View style={styles.tashkeelRow}>
          {tashkeelLetters.slice(0, 5).map((item, index) => (
            <KeyButton
              key={`tashkeel-${index}`}
              letter={item.label}
              onPress={() => handleLetterPress(item.key)}
              style={styles.tashkeelKey}
              textStyle={styles.tashkeelText}
              isTashkeelKey
            />
          ))}
        </View>
        <View style={styles.tashkeelRow}>
          {tashkeelLetters.slice(5).map((item, index) => (
            <KeyButton
              key={`tashkeel-${index + 5}`}
              letter={item.label}
              onPress={() => handleLetterPress(item.key)}
              style={styles.tashkeelKey}
              textStyle={styles.tashkeelText}
              isTashkeelKey
            />
          ))}
        </View>
        {arabicLetters.map((row, rowIndex) => (
          <View key={`arabic-${rowIndex}`} style={styles.keyboardRow}>
            {row.map((letter, letterIndex) => (
              <KeyButton
                key={`arabic-${rowIndex}-${letterIndex}`}
                letter={letter}
                onPress={() => handleLetterPress(letter)}
                style={styles.keyboardKey}
                textStyle={styles.keyboardText}
              />
            ))}
          </View>
        ))}
      </View>
      {showSuccess && (
        <View style={styles.popup}>
          <Text style={styles.popupText}>✅</Text>
          <Text style={styles.popupSubtext}>أحسنت!</Text>
        </View>
      )}
      {showComplete && (
        <View style={[styles.popup, { backgroundColor: 'rgba(0, 122, 255, 0.95)' }]}>
          <Text style={[styles.popupText, { fontSize: 36 }]}>لقد أتممتم جميع التمارين</Text>
          <Text style={styles.popupSubtext}>هل تريدون الإعادة مرة أخرى؟</Text>
          <View style={{ flexDirection: 'row', marginTop: 32, gap: 20 }}>
            <Pressable style={[styles.popupButton, { backgroundColor: '#fff' }]} onPress={async () => {
              await AsyncStorage.removeItem(`correctWords_${level}`);
              setShowComplete(false);
              setCorrectWords([]);
            }}>
              <Text style={[styles.popupButtonText, { color: '#007AFF' }]}>نعم</Text>
            </Pressable>
            <Pressable style={[styles.popupButton, { backgroundColor: '#fff' }]} onPress={() => router.back()}>
              <Text style={[styles.popupButtonText, { color: '#007AFF' }]}>لا</Text>
            </Pressable>
          </View>
        </View>
      )}
    </View>
  );
}

